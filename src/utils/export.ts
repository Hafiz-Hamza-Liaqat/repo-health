import { RepoHealthReport } from '../types/report';

export function downloadReportJson(report: RepoHealthReport): void {
  const jsonString = JSON.stringify(report, null, 2);
  const blob = new Blob([jsonString], { type: 'application/json' });
  const url = URL.createObjectURL(blob);

  const dateStr = new Date().toISOString().slice(0, 10);
  const filename = `repohealth-${report.repository.owner}-${report.repository.name}-${dateStr}.json`;

  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function generateMarkdownSummary(report: RepoHealthReport): string {
  const repo = report.repository;
  const score = report.scoring.assessment;
  const categories = Object.values(score.categoryScores);

  const lines: string[] = [
    `# RepoHealth Assessment: ${repo.fullName}`,
    `**Evaluated on:** ${new Date(report.generatedAt).toUTCString()}  `,
    `**Repository:** [${repo.fullName}](${repo.url})  `,
    `**Overall Health Score:** **${score.totalScore}/100** (Grade: **${score.grade}**)  `,
    `**Perspective:** ${score.perspective.name}  `,
    '',
    '## Category Breakdown',
    '| Category | Score | Weight | Status |',
    '| :--- | :--- | :--- | :--- |',
  ];

  categories.forEach((cat) => {
    const status = cat.isApplicable
      ? `${cat.earnedPoints}/${cat.maxPoints} pts (${cat.percentage}%)`
      : 'N/A (Excluded)';
    lines.push(`| ${cat.label} | ${status} | ${cat.weight} pts | ${cat.percentage >= 70 ? '✅ Pass' : cat.percentage >= 40 ? '⚠️ Warning' : '❌ Needs Attention'} |`);
  });

  lines.push('');
  lines.push('## Technology Stack Detected');
  if (report.technologies.length > 0) {
    report.technologies.forEach((tech) => {
      lines.push(`- **${tech.name}** (${tech.category}): ${tech.confidence.replace(/_/g, ' ')}`);
    });
  } else {
    lines.push('- No specific frameworks confirmed from manifests');
  }

  if (report.securityHygiene && report.securityHygiene.findings.length > 0) {
    lines.push('');
    lines.push('## Security & Supply-Chain Hygiene (Preliminary)');
    const { summary, coverage } = report.securityHygiene;
    const summaryParts = [
      `Pass: ${summary.passCount}`,
      summary.issueCount > 0 ? `Issue: ${summary.issueCount}` : null,
      summary.warningCount > 0 ? `Warning: ${summary.warningCount}` : null,
      summary.notDetectedCount > 0 ? `Not Detected: ${summary.notDetectedCount}` : null,
      summary.unknownCount > 0 ? `Indeterminate: ${summary.unknownCount}` : null,
      summary.notApplicableCount > 0 ? `Not Applicable: ${summary.notApplicableCount}` : null,
    ].filter(Boolean).join(' | ');

    lines.push(`*Summary:* ${summaryParts}`);
    if (coverage.workflowCoverage) {
      lines.push(
        `*Workflow Retrieval Coverage:* ${coverage.workflowCoverage.status.toUpperCase()} (${coverage.workflowCoverage.retrievedCount}/${coverage.workflowCoverage.discoveredCount} workflows retrieved, ${coverage.workflowCoverage.totalBytesRetrieved} bytes)`
      );
    }
    lines.push('');

    report.securityHygiene.findings.forEach((f) => {
      let statusIcon = '⚪ Not Detected';
      if (f.status === 'pass') statusIcon = '✅ Pass';
      else if (f.status === 'issue') statusIcon = '❌ Issue';
      else if (f.status === 'warning') statusIcon = '⚠️ Warning';
      else if (f.status === 'unknown') statusIcon = '❓ Unknown';
      else if (f.status === 'not_applicable') statusIcon = '➖ Not Applicable';
      else if (f.status === 'not_detected') statusIcon = '⚪ Not Detected';

      const location = f.evidence?.sourcePath
        ? ` (${f.evidence.sourcePath}${f.evidence.line ? `:${f.evidence.line}` : ''})`
        : '';
      lines.push(`- **[${f.ruleId}] ${f.title}:** ${statusIcon}${location} — ${f.explanation}`);
    });
  }

  lines.push('');
  lines.push('## Key Recommendations');
  if (report.recommendations.length > 0) {
    report.recommendations.slice(0, 5).forEach((rec, i) => {
      lines.push(`${i + 1}. **[${rec.priority.toUpperCase()}] ${rec.title}:** ${rec.action}`);
    });
  } else {
    lines.push('No critical issues detected. Repository adheres to core health practices.');
  }

  lines.push('');
  lines.push('---');
  lines.push('*Generated by [RepoHealth](https://github.com/repo-health) — Transparent, evidence-based repository assessments.*');

  return lines.join('\n');
}

export function printReport(): void {
  window.print();
}

export async function copyToClipboard(text: string): Promise<boolean> {
  if (navigator?.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Fall through to fallback
    }
  }

  try {
    const textArea = document.createElement('textarea');
    textArea.value = text;
    textArea.style.position = 'fixed';
    textArea.style.left = '-9999px';
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    const successful = document.execCommand('copy');
    document.body.removeChild(textArea);
    return successful;
  } catch {
    return false;
  }
}
